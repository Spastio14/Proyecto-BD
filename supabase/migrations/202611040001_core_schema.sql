-- Esquema estructural PostgreSQL. No contiene datos de prueba.

begin;

set local timezone = 'UTC';

create table public.persona (
    id_persona integer generated by default as identity,
    nombres varchar(120) not null,
    apellidos varchar(120),
    telefono_contacto varchar(30),
    correo_electronico varchar(254),
    documento_identificacion varchar(120),
    constraint pk_persona primary key (id_persona),
    constraint ck_persona_nombres check (btrim(nombres) <> ''),
    constraint ck_persona_correo check (
        correo_electronico is null
        or correo_electronico like '%_@_%._%'
    )
);

create table public.cuenta_acceso (
    id_cuenta integer generated by default as identity,
    id_persona integer not null,
    identificador_autenticacion varchar(255) not null,
    fecha_activacion timestamptz not null,
    estado_cuenta varchar(80) not null,
    ultimo_acceso timestamptz,
    constraint pk_cuenta_acceso primary key (id_cuenta),
    constraint uq_cuenta_acceso_persona unique (id_persona),
    constraint uq_cuenta_acceso_auth unique (identificador_autenticacion),
    constraint ck_cuenta_estado check (
        estado_cuenta in ('ACTIVA', 'SUSPENDIDA', 'BLOQUEADA')
    )
);

create table public.cliente (
    id_persona integer not null,
    tipo_cliente varchar(80) not null,
    condicion_comercial varchar(255) not null,
    fecha_registro timestamptz not null,
    origen_registro varchar(80) not null,
    estado varchar(80) not null,
    constraint pk_cliente primary key (id_persona),
    constraint ck_cliente_tipo check (
        tipo_cliente in ('INVITADO', 'REGISTRADO', 'EMPRESA')
    ),
    constraint ck_cliente_estado check (estado in ('ACTIVO', 'INACTIVO'))
);

create table public.empleado (
    id_persona integer not null,
    codigo_empleado varchar(64) not null,
    fecha_ingreso timestamptz not null,
    estado_laboral varchar(80) not null,
    capacidad_maxima_asignaciones integer not null,
    constraint pk_empleado primary key (id_persona),
    constraint uq_empleado_codigo unique (codigo_empleado),
    constraint ck_empleado_capacidad check (capacidad_maxima_asignaciones >= 0),
    constraint ck_empleado_estado check (
        estado_laboral in ('ACTIVO', 'INACTIVO', 'SUSPENDIDO')
    )
);

create table public.asignacion_rol (
    id_asignacion_rol integer generated by default as identity,
    id_empleado integer not null,
    id_rol integer not null,
    fecha_asignacion timestamptz not null,
    fecha_finalizacion timestamptz,
    estado varchar(80) not null,
    constraint pk_asignacion_rol primary key (id_asignacion_rol),
    constraint ck_asignacion_rol_fechas check (
        fecha_finalizacion is null or fecha_finalizacion >= fecha_asignacion
    ),
    constraint ck_asignacion_rol_estado check (estado in ('ACTIVA', 'FINALIZADA'))
);

create table public.rol (
    id_rol integer generated by default as identity,
    nombre varchar(180) not null,
    descripcion varchar(500) not null,
    estado varchar(80) not null,
    constraint pk_rol primary key (id_rol),
    constraint uq_rol_nombre unique (nombre),
    constraint ck_rol_estado check (estado in ('ACTIVO', 'INACTIVO'))
);

create table public.rol_permiso (
    id_rol integer not null,
    id_permiso integer not null,
    constraint pk_rol_permiso primary key (id_rol, id_permiso)
);

create table public.permiso (
    id_permiso integer generated by default as identity,
    codigo_permiso varchar(64) not null,
    descripcion varchar(500) not null,
    modulo varchar(255) not null,
    constraint pk_permiso primary key (id_permiso),
    constraint uq_permiso_codigo unique (codigo_permiso)
);

create table public.cotizacion (
    id_cotizacion integer generated by default as identity,
    id_cliente integer not null,
    fecha_emision timestamptz not null,
    fecha_vencimiento timestamptz not null,
    estado varchar(80) not null,
    total_ofrecido numeric(19,2) not null,
    observaciones text,
    constraint pk_cotizacion primary key (id_cotizacion),
    constraint uq_cotizacion_cliente unique (id_cotizacion, id_cliente),
    constraint ck_cotizacion_total check (total_ofrecido >= 0),
    constraint ck_cotizacion_fechas check (fecha_vencimiento >= fecha_emision),
    constraint ck_cotizacion_estado check (
        estado in ('BORRADOR', 'EMITIDA', 'ACEPTADA', 'RECHAZADA', 'VENCIDA')
    )
);

create table public.pedido (
    id_pedido integer generated by default as identity,
    id_cliente integer not null,
    id_empleado_registro integer,
    id_etapa_actual integer,
    id_cotizacion integer,
    codigo_pedido varchar(64) not null,
    fecha_creacion timestamptz not null,
    vencimiento_pago timestamptz not null,
    fecha_inicio_revision_pago timestamptz,
    canal_origen varchar(80) not null,
    estado varchar(80) not null,
    fecha_entrega_prevista timestamptz not null,
    modalidad_entrega varchar(80) not null,
    nombre_persona_retiro varchar(120),
    total_pedido numeric(19,2) not null default 0,
    token_seguimiento uuid not null default gen_random_uuid(),
    constraint pk_pedido primary key (id_pedido),
    constraint uq_pedido_cotizacion unique (id_cotizacion),
    constraint uq_pedido_codigo unique (codigo_pedido),
    constraint uq_pedido_token unique (token_seguimiento),
    constraint ck_pedido_fechas check (
        vencimiento_pago >= fecha_creacion
        and fecha_entrega_prevista >= fecha_creacion
    ),
    constraint ck_pedido_ventana_inicial check (
        vencimiento_pago = fecha_creacion + interval '24 hours'
    ),
    constraint ck_pedido_revision_pago check (
        fecha_inicio_revision_pago is null
        or fecha_inicio_revision_pago between fecha_creacion and vencimiento_pago
    ),
    constraint ck_pedido_estado check (
        estado in (
            'PENDIENTE_PAGO', 'PAGADO_PARCIAL', 'PAGADO', 'EN_DISENO',
            'EN_PRODUCCION', 'LISTO', 'ENTREGADO', 'CANCELADO', 'EXPIRADO'
        )
    ),
    constraint ck_pedido_entrega check (modalidad_entrega in ('RETIRO', 'ENVIO')),
    constraint ck_pedido_total check (total_pedido >= 0)
);

create table public.historial_pedido (
    id_historial integer generated by default as identity,
    id_pedido integer not null,
    id_empleado integer,
    id_etapa_anterior integer,
    id_etapa_nueva integer,
    fecha_hora timestamptz not null,
    estado_anterior varchar(80),
    estado_nuevo varchar(80) not null,
    motivo varchar(500),
    origen_cambio varchar(80) not null,
    constraint pk_historial_pedido primary key (id_historial),
    constraint ck_historial_origen check (
        origen_cambio in ('EMPLEADO', 'CLIENTE', 'SISTEMA')
    ),
    constraint ck_historial_estado_nuevo check (
        estado_nuevo in (
            'PENDIENTE_PAGO', 'PAGADO_PARCIAL', 'PAGADO', 'EN_DISENO',
            'EN_PRODUCCION', 'LISTO', 'ENTREGADO', 'CANCELADO', 'EXPIRADO'
        )
    )
);

create table public.detalle_cotizacion (
    id_cotizacion integer not null,
    numero_linea integer not null,
    id_variante integer not null,
    cantidad integer not null,
    descripcion_personalizacion text,
    precio_ofrecido numeric(19,2) not null,
    descuento_ofrecido numeric(19,2) not null default 0,
    constraint pk_detalle_cotizacion primary key (id_cotizacion, numero_linea),
    constraint ck_det_cot_linea check (numero_linea > 0),
    constraint ck_det_cot_cantidad check (cantidad > 0),
    constraint ck_det_cot_precio check (precio_ofrecido >= 0),
    constraint ck_det_cot_descuento check (
        descuento_ofrecido >= 0
        and descuento_ofrecido <= precio_ofrecido * cantidad
    )
);

create table public.detalle_pedido (
    id_pedido integer not null,
    numero_linea integer not null,
    id_variante integer not null,
    cantidad integer not null,
    precio_unitario_aplicado numeric(19,2) not null,
    descuento_aplicado numeric(19,2) not null default 0,
    importe_pactado numeric(19,2) not null,
    costo_estimado numeric(19,2) not null,
    costo_real_consolidado numeric(19,2),
    modo_precio varchar(20) not null,
    id_promocion integer,
    constraint pk_detalle_pedido primary key (id_pedido, numero_linea),
    constraint ck_det_pedido_linea check (numero_linea > 0),
    constraint ck_det_pedido_cantidad check (cantidad > 0),
    constraint ck_det_pedido_precio check (precio_unitario_aplicado >= 0),
    constraint ck_det_pedido_descuento check (
        descuento_aplicado >= 0
        and descuento_aplicado <= precio_unitario_aplicado * cantidad
    ),
    constraint ck_det_pedido_importe check (importe_pactado >= 0),
    constraint ck_det_pedido_costo_estimado check (costo_estimado >= 0),
    constraint ck_det_pedido_costo_real check (
        costo_real_consolidado is null or costo_real_consolidado >= 0
    ),
    constraint ck_det_pedido_modo check (
        modo_precio in (
            'DETALLE', 'MAYORISTA', 'PROMOCION', 'MAYORISTA_PROMO', 'COTIZADO'
        )
    ),
    constraint ck_det_pedido_promocion check (
        (modo_precio in ('PROMOCION', 'MAYORISTA_PROMO')) = (id_promocion is not null)
    )
);

create table public.etapa_proceso (
    id_etapa integer generated by default as identity,
    nombre varchar(180) not null,
    descripcion varchar(500),
    orden_referencia integer not null,
    estado varchar(80) not null,
