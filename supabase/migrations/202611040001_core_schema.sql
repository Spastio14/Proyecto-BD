create table public.transaccion (
    id_transaccion integer generated by default as identity,
    id_pedido integer not null,
    numero_hito integer,
    id_empleado_verificador integer,
    id_transaccion_compensada integer,
    id_reembolso integer,
    fecha_hora timestamptz not null,
    tipo_transaccion varchar(80) not null,
    monto_con_signo numeric(19,2) not null,
    metodo_pago varchar(80) not null,
    banco_receptor varchar(120),
    referencia_bancaria varchar(120),
    estado_verificacion varchar(80) not null,
    clave_idem uuid not null,
    constraint pk_transaccion primary key (id_transaccion),
    constraint uq_transaccion_idem unique (clave_idem),
    constraint uq_transaccion_pedido unique (id_transaccion, id_pedido),
    constraint ck_transaccion_hito check (numero_hito is null or numero_hito > 0),
    constraint ck_transaccion_monto check (monto_con_signo <> 0),
    constraint ck_transaccion_compensada check (
        id_transaccion_compensada is null
        or id_transaccion_compensada <> id_transaccion
    ),
    constraint ck_transaccion_estado check (
        estado_verificacion in ('PENDIENTE', 'VERIFICADO', 'RECHAZADO')
    ),
    constraint ck_transaccion_metodo check (
        metodo_pago in ('EFECTIVO', 'TRANSFERENCIA', 'TARJETA', 'OTRO')
    ),
    constraint ck_transaccion_tipo check (
        tipo_transaccion in ('PAGO', 'REEMBOLSO', 'COMPENSACION')
    ),
    constraint ck_transaccion_signo check (
        (tipo_transaccion = 'PAGO' and monto_con_signo > 0)
        or (tipo_transaccion = 'REEMBOLSO' and monto_con_signo < 0)
        or tipo_transaccion = 'COMPENSACION'
    )
);

create table public.cancelacion (
    id_cancelacion integer generated by default as identity,
    id_pedido integer not null,
    id_empleado_autoriza integer,
    fecha_hora timestamptz not null,
    motivo varchar(500) not null,
    etapa_cancelacion varchar(255) not null,
