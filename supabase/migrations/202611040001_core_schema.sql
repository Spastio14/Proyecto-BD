    constraint pk_cancelacion primary key (id_cancelacion),
    constraint uq_cancelacion_pedido unique (id_pedido),
    constraint ck_cancelacion_monto check (monto_retenido >= 0),
    constraint ck_cancelacion_resultado check (
        resultado in ('PENDIENTE', 'APROBADA', 'RECHAZADA')
    )
);

