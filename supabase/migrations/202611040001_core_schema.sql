create table public.promocion (
    id_promocion integer generated by default as identity,
    nombre varchar(180) not null,
    tipo varchar(255) not null,
    cantidad_requerida integer not null,
    beneficio text not null,
    fecha_inicio timestamptz not null,
    fecha_fin timestamptz not null,
    condiciones text,
    permite_combinacion_mayorista boolean not null,
    valor_beneficio numeric(19,2) not null,
    estado varchar(20) not null,
    constraint pk_promocion primary key (id_promocion),
    constraint ck_promocion_cantidad check (cantidad_requerida > 0),
    constraint ck_promocion_fechas check (fecha_fin >= fecha_inicio),
    constraint ck_promocion_tipo check (
        tipo in ('PRECIO_PAQUETE', 'DESCUENTO_FIJO', 'PORCENTAJE')
    ),
    constraint ck_promocion_valor check (
        (tipo = 'PORCENTAJE' and valor_beneficio >= 0 and valor_beneficio <= 100)
        or (tipo = 'PRECIO_PAQUETE' and valor_beneficio > 0)
        or (tipo = 'DESCUENTO_FIJO' and valor_beneficio >= 0)
    ),
    constraint ck_promocion_estado check (estado in ('ACTIVA', 'INACTIVA'))
);

