-- Fase 4.5.3: abonos parciales, distribución contable y control de caja.
-- Conserva TRANSACCION como el movimiento monetario único y distribuye su
-- importe entre uno o varios hitos sin duplicar ingresos.

begin;

alter table public.transaccion
    add column banco_origen varchar(120),
    add column fecha_verificacion timestamptz;

create table public.aplicacion_transaccion_hito (
    id_transaccion integer not null,
    id_pedido integer not null,
    numero_hito integer not null,
    monto_aplicado numeric(19,2) not null,
    constraint pk_aplicacion_transaccion_hito
        primary key (id_transaccion, numero_hito),
    constraint fk_aplicacion_transaccion
        foreign key (id_transaccion, id_pedido)
        references public.transaccion (id_transaccion, id_pedido),
    constraint fk_aplicacion_hito
        foreign key (id_pedido, numero_hito)
        references public.hito_pago (id_pedido, numero_hito),
    constraint ck_aplicacion_monto_positivo check (monto_aplicado > 0)
);

insert into public.aplicacion_transaccion_hito
    (id_transaccion, id_pedido, numero_hito, monto_aplicado)
select
    id_transaccion,
    id_pedido,
    numero_hito,
    monto_con_signo
from public.transaccion
where tipo_transaccion = 'PAGO'
  and numero_hito is not null
  and monto_con_signo > 0
on conflict do nothing;

create index ix_aplicacion_hito
    on public.aplicacion_transaccion_hito (id_pedido, numero_hito);

create table public.caja (
    id_caja integer generated by default as identity,
    id_empleado_apertura integer not null,
    id_empleado_cierre integer,
    fecha_apertura timestamptz not null,
    fecha_cierre timestamptz,
    saldo_inicial numeric(19,2) not null,
    saldo_cierre_declarado numeric(19,2),
    estado varchar(20) not null,
    constraint pk_caja primary key (id_caja),
    constraint fk_caja_empleado_apertura
        foreign key (id_empleado_apertura) references public.empleado (id_persona),
    constraint fk_caja_empleado_cierre
        foreign key (id_empleado_cierre) references public.empleado (id_persona),
    constraint ck_caja_saldos check (
        saldo_inicial >= 0
        and (saldo_cierre_declarado is null or saldo_cierre_declarado >= 0)
    ),
    constraint ck_caja_estado check (estado in ('ABIERTA', 'CERRADA')),
    constraint ck_caja_cierre check (
        (estado = 'ABIERTA' and fecha_cierre is null and id_empleado_cierre is null
            and saldo_cierre_declarado is null)
        or
        (estado = 'CERRADA' and fecha_cierre is not null and id_empleado_cierre is not null
            and saldo_cierre_declarado is not null)
    )
);

create unique index uq_caja_unica_abierta
    on public.caja ((estado)) where estado = 'ABIERTA';

create table public.movimiento_caja (
    id_movimiento_caja integer generated by default as identity,
    id_caja integer not null,
    id_transaccion integer not null,
    id_empleado integer not null,
    fecha_hora timestamptz not null,
    tipo_movimiento varchar(40) not null,
    monto numeric(19,2) not null,
    folio_recibo varchar(80) not null,
    constraint pk_movimiento_caja primary key (id_movimiento_caja),
    constraint uq_movimiento_caja_transaccion unique (id_transaccion),
    constraint uq_movimiento_caja_folio unique (folio_recibo),
    constraint fk_movimiento_caja_caja
        foreign key (id_caja) references public.caja (id_caja),
    constraint fk_movimiento_caja_transaccion
        foreign key (id_transaccion) references public.transaccion (id_transaccion),
    constraint fk_movimiento_caja_empleado
        foreign key (id_empleado) references public.empleado (id_persona),
    constraint ck_movimiento_caja_tipo check (tipo_movimiento = 'INGRESO_PAGO'),
    constraint ck_movimiento_caja_monto check (monto > 0),
    constraint ck_movimiento_caja_folio check (btrim(folio_recibo) <> '')
);

create index ix_movimiento_caja_fecha
    on public.movimiento_caja (id_caja, fecha_hora desc);

alter table public.aplicacion_transaccion_hito enable row level security;
alter table public.caja enable row level security;
alter table public.movimiento_caja enable row level security;

revoke all on table public.aplicacion_transaccion_hito from public, anon, authenticated;
revoke all on table public.caja from public, anon, authenticated;
revoke all on table public.movimiento_caja from public, anon, authenticated;
revoke all on sequence public.caja_id_caja_seq from public, anon, authenticated;
revoke all on sequence public.movimiento_caja_id_movimiento_caja_seq
    from public, anon, authenticated;

commit;
