-- Roles supplied by Supabase in hosted projects and created only for local tests.
do $$
begin
    if not exists (select 1 from pg_roles where rolname = 'anon') then
        create role anon nologin;
    end if;
    if not exists (select 1 from pg_roles where rolname = 'authenticated') then
        create role authenticated nologin;
    end if;
end
$$;

-- Aproximación mínima del esquema Storage administrado por Supabase. Permite
-- comprobar que nuestras migraciones configuran buckets sin cambiar grants
-- globales sobre storage.buckets u storage.objects.
create schema if not exists storage;

create table if not exists storage.buckets (
    id text primary key,
    name text not null unique,
    public boolean not null default false,
    file_size_limit bigint,
    allowed_mime_types text[]
);

create table if not exists storage.objects (
    id bigint generated by default as identity primary key,
    bucket_id text not null references storage.buckets (id),
    name text not null
);

alter table storage.buckets enable row level security;
alter table storage.objects enable row level security;

grant usage on schema storage to anon, authenticated;
grant select on storage.buckets to anon, authenticated;
grant select, insert on storage.objects to anon, authenticated;
